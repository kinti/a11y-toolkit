#!/usr/bin/env python3
"""RGAA 4.1 — the French legal standard as data.

Generated by scripts/rgaa_ingest.py from the OFFICIAL government JSON
(github.com/DISIC/accessibilite.numerique.gouv.fr — open data, 106/106
criteria with a mechanical bridge to WCAG SC). This module is the thin
loader + the lookup surfaces other modules use; never hand-edit the JSON.

The RGAA has its own numbering (1.1–13.12 across 13 topics) and NO A/AA
levels — every criterion is conformant / not conformant. Titles and tests
are French (the standard's language); the WCAG bridge lives in each
criterion's `wcag` list.
"""

import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))

with open(os.path.join(_HERE, 'rgaa.json'), encoding='utf-8') as _f:
    _DATA = json.load(_f)

STANDARD_NAME = 'RGAA 4.1 (France)'
VERSION = _DATA['version']
WCAG_BASE = _DATA['wcag_base']
SOURCE = _DATA['source']
TOPICS = [(t['number'], t['name']) for t in _DATA['topics']]
CRITERIA = _DATA['criteria']   # 106: {num, topic, number, title, tests, notes, wcag}

# índice inverso: WCAG SC code → [números RGAA] (el puente mecánico)
_BY_SC = {}
for _c in CRITERIA:
    for _w in _c['wcag']:
        _sc = _w.split(' ')[0]
        _BY_SC.setdefault(_sc, []).append(_c['num'])


def rgaa_for_sc(sc_code):
    """'1.1.1' → ['1.1', …]: los criterios RGAA que verifican ese SC.
    Devuelve [] si ningún criterio RGAA lo referencia."""
    return list(_BY_SC.get(sc_code, []))


def criterion(num):
    """'1.1' → el criterio completo, o None."""
    return next((c for c in CRITERIA if c['num'] == num), None)


def standard_block(lang='en'):
    """Bloque 'standard' para informes audit --standard rgaa."""
    names = {'en': 'RGAA 4.1 — the French web accessibility framework',
             'es': 'RGAA 4.1 — el marco francés de accesibilidad web'}
    return {
        'name': names.get(lang) or names['en'],
        'version': VERSION,
        'topics': len(TOPICS),
        'criteria': len(CRITERIA),
        'wcag_base': WCAG_BASE,
        'source': SOURCE,
    }
